function lunarText(y,m,d){ // 用于日历小字：节日优先
  const lf = lunarFest[m+"-"+d];
  if(lf) return lf;
  const sf = solarFest[m+"-"+d];
  if(sf) return sf;
  const L = solar2lunar(new Date(y,m-1,d));
  if(L.day===1) return L.monthCN;
  const lf2 = lunarFest[L.month+"-"+L.day];
  return lf2 || L.dayCN;
}
